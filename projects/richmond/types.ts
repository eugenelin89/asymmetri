export type Point = [number, number];
export type Polygon = Point[][];
export type Pose = { x: number; z: number; y: number; yaw: number };
export type Road = {
  id: string;
  name: string;
  points: Point[];
  nodes: number[];
  heights: number[];
  width: number;
  kind: "road" | "path" | "airfield";
  bridge: boolean;
  oneway: number;
  class: string;
};
export type Building = {
  id: string;
  shape: Polygon;
  height: number;
  heightMethod: string;
  name: string;
  kind: string;
};
export type Place = {
  entrances?: { id: string; point: Point; parking: Point }[];
  id: string;
  name: string;
  district: string;
  point: Point;
  entrance: Point;
  parking: Point;
  roadNode: number;
  building: string | null;
  interior: "restaurant" | "mall" | "terminal" | "office" | "lobby" | null;
  role: "pickup" | "customer" | "landmark";
  label: string;
  source: string;
};
export type City = {
  version: string;
  bounds: [number, number, number, number];
  origin: Point;
  roads: Road[];
  nodes: [number, number, number][];
  edges: {
    a: number;
    b: number;
    road: number;
    length: number;
    direction: number;
  }[];
  water: Polygon[];
  land: Polygon[];
  parks: { name: string; shape: Polygon; kind: string }[];
  lots: { id: string; shape: Polygon; airfield: boolean }[];
  places: Place[];
  buildingIndex: {
    id: string;
    bounds: [number, number, number, number];
    shape: Polygon;
    height: number;
  }[];
  tiles: {
    id: string;
    url: string;
    bounds: [number, number, number, number];
    count: number;
  }[];
  airportGate: { road: Point; apron: Point; shape: Polygon };
};
export type CameraMode = "third" | "first" | "top" | "aerial";
export type Input = "forward" | "back" | "left" | "right" | "sprint" | "brake";
export type Order = {
  id: string;
  mission: string;
  title: string;
  food: string;
  pickup: string;
  destination: string;
  customer: string;
  basePay: number;
  distance: number;
  duration: number;
  remaining: number;
  condition: number;
  stage: "accepted" | "collected";
};
export type Receipt = {
  id: string;
  title: string;
  pay: number;
  tip: number;
  rating: number;
  outcome: "delivered" | "cancelled" | "expired" | "stolen";
};
export type Encounter = {
  id: string;
  kind: "pickpocket" | "scam" | "robbery" | "breakin" | "hazard";
  origin: Point;
  remaining: number;
  warning: string;
};
export type Settings = {
  gentle: boolean;
  encounterRate: number;
  encounterSeverity: number;
  lite: boolean;
  density: number;
  reducedMotion: boolean;
  northUp: boolean;
  locale: "en" | "zh";
  textScale: number;
};
export type State = {
  version: 1;
  map: string;
  player: Pose;
  car: Pose & {
    speed: number;
    steer: number;
    condition: number;
    blocked: boolean;
  };
  locomotion: "walk" | "drive";
  interior: { place: string; entrance: Point } | null;
  camera: CameraMode;
  airfield: boolean;
  cash: number;
  health: number;
  stamina: number;
  inventory: Record<string, number>;
  active: Order | null;
  history: Receipt[];
  ledger: string[];
  sequence: number;
  rng: number;
  elapsed: number;
  cooldown: number;
  encounter: Encounter | null;
  resolved: number;
  settings: Settings;
  checkpoint: Pose;
  tutorial: number;
  shopping: boolean;
};
export type Mission = {
  id: string;
  title: string;
  food: string;
  pickup: string;
  destination: string;
  customer: string;
  description: string;
};
export type Interior = {
  width: number;
  depth: number;
  spawn: Point;
  exit: Point;
  alternateExit?: Point;
  pickup: Point;
  customer: Point;
  shops: { id: string; name: string; point: Point }[];
  obstacles: [number, number, number, number][];
  zones: { name: string; point: Point }[];
};
export type Snapshot = {
  state: State;
  message: string;
  prompt: string;
  street: string;
  route: Point[];
  target: Point | null;
  objective: string;
  paused: boolean;
  fps: number;
  pedestrians: number;
  traffic: number;
  saveNotice: string;
  distance: number;
};
export type Game = {
  input(action: Input, pressed: boolean, source: string): void;
  interact(): void;
  vehicle(): void;
  accept(id: string): void;
  cancel(): void;
  buy(id: string): void;
  use(id: string): void;
  camera(mode: CameraMode): void;
  focus(target: "player" | "car" | string): void;
  navigate(id: string): void;
  look(x: number, y: number): void;
  lockPointer(): void;
  zoom(delta: number): void;
  airfield(value: boolean): void;
  encounter(choice: "leave" | "help" | "give"): void;
  settings(value: Partial<Settings>): void;
  pause(value: boolean): void;
  recover(): void;
  save(): void;
  reset(): void;
  dispose(): void;
};
