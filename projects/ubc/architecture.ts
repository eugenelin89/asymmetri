export type ArchitectureKind = "rose" | "bookstore" | "nest" | "sauder";
export function architectureEnvelope(
  kind: ArchitectureKind,
  source: Anchor,
): Anchor {
  // The Nest footprint is irregular: its bounding rectangle overlaps the
  // Alumni Centre. Support a smaller central public-space reconstruction until
  // a footprint-conforming bespoke exterior replaces this rectangular model.
  return {
    ...source,
    width: kind === "nest" ? Math.min(source.width, 76) : source.width,
  };
}
export type ArchitectureCollider = {
  minX: number;
  maxX: number;
  minZ: number;
  maxZ: number;
  minY: number;
  maxY: number;
};
export type ArchitectureFloor = {
  minX: number;
  maxX: number;
  minZ: number;
  maxZ: number;
  y: number;
};
export type ArchitectureRamp = {
  minX: number;
  maxX: number;
  minZ: number;
  maxZ: number;
  fromY: number;
  toY: number;
  axis: "x" | "z";
};
export type ArchitectureDisplay = {
  id: string;
  x: number;
  y: number;
  z: number;
};
export type Architecture = {
  group: THREE.Group;
  colliders: ArchitectureCollider[];
  floors: ArchitectureFloor[];
  ramps: ArchitectureRamp[];
  displays: ArchitectureDisplay[];
  entry: [number, number];
  interiorBounds: { width: number; depth: number };
};

type MaterialName =
  | "stone"
  | "concrete"
  | "timber"
  | "darkWood"
  | "metal"
  | "white"
  | "glass"
  | "roof"
  | "turf"
  | "clay"
  | "blue"
  | "fabric"
  | "light"
  | "redBook"
  | "goldBook"
  | "blueBook"
  | "whiteBook"
  | "greenBook"
  | "net";

/** Small, original deterministic grain maps: generated bytes, no network assets. */
function grainTexture(kind: "timber" | "stone" | "turf") {
  const size = 64,
    bytes = new Uint8Array(size * size * 4);
  let state = 1943;
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
      const noise = (state >>> 24) / 255;
      const grain =
        kind === "timber"
          ? 0.76 +
            Math.sin(x * 1.8 + Math.sin(y * 0.09) * 0.4) * 0.08 +
            noise * 0.14
          : 0.84 + noise * 0.16;
      const at = (y * size + x) * 4;
      bytes[at] = bytes[at + 1] = bytes[at + 2] = Math.round(grain * 255);
      bytes[at + 3] = 255;
    }
  const texture = new THREE.DataTexture(bytes, size, size, THREE.RGBAFormat);
  texture.colorSpace = THREE.SRGBColorSpace;
  texture.wrapS = texture.wrapT = THREE.RepeatWrapping;
  texture.repeat.set(kind === "timber" ? 5 : 8, kind === "turf" ? 16 : 4);
  texture.magFilter = THREE.LinearFilter;
  texture.minFilter = THREE.LinearMipmapLinearFilter;
  texture.generateMipmaps = true;
  texture.needsUpdate = true;
  return texture;
}

/** One merged mesh per material keeps detailed furniture inexpensive to draw. */
class Builder {
  readonly group = new THREE.Group();
  readonly colliders: ArchitectureCollider[] = [];
  readonly floors: ArchitectureFloor[] = [];
  readonly ramps: ArchitectureRamp[] = [];
  readonly displays: ArchitectureDisplay[] = [];
  readonly materials: Record<MaterialName, THREE.MeshStandardMaterial>;
  private readonly buckets = new Map<MaterialName, THREE.BufferGeometry[]>();
  private readonly unitBox = new THREE.BoxGeometry(1, 1, 1);
  private readonly unitCylinder = new THREE.CylinderGeometry(1, 1, 1, 8);
  private readonly matrix = new THREE.Matrix4();
  private readonly position = new THREE.Vector3();
  private readonly scale = new THREE.Vector3();
  private readonly quaternion = new THREE.Quaternion();
  constructor(
    readonly width: number,
    readonly depth: number,
    readonly sourceHeight?: number,
  ) {
    const standard = (color: number, roughness = 0.7, metalness = 0) =>
      new THREE.MeshStandardMaterial({ color, roughness, metalness });
    this.materials = {
      stone: standard(0xc6b9a1),
      concrete: standard(0xb9b6ad),
      timber: standard(0xb78551),
      darkWood: standard(0x5e4936),
      metal: standard(0x34434a, 0.38, 0.68),
      white: standard(0xe8e4d9),
      glass: new THREE.MeshStandardMaterial({
        color: 0x9cbabc,
        transparent: true,
        opacity: 0.25,
        roughness: 0.16,
        metalness: 0.3,
        side: THREE.DoubleSide,
        depthWrite: false,
      }),
      roof: standard(0x465157, 0.62, 0.3),
      turf: standard(0x3f6741),
      clay: standard(0x99684d),
      blue: standard(0x254e70),
      fabric: standard(0x557370),
      light: new THREE.MeshStandardMaterial({
        color: 0xffeed1,
        emissive: 0xffebcc,
        emissiveIntensity: 2.2,
        roughness: 0.6,
      }),
      redBook: standard(0x8f554f),
      goldBook: standard(0xc6a568),
      blueBook: standard(0x4b718a),
      whiteBook: standard(0xdcd4bb),
      greenBook: standard(0x657c62),
      net: standard(0x293a34, 0.95),
    };
    this.materials.timber.map = grainTexture("timber");
    this.materials.concrete.map = grainTexture("stone");
    this.materials.turf.map = grainTexture("turf");
    this.group.userData = {
      reconstruction: "B",
      originalProceduralAsset: true,
      sourceHeight: sourceHeight ?? null,
      heightInterpretation:
        "Source maximum height informs exterior massing; interior floor heights and lower roof proportions are reconstructed.",
    };
  }
  private addGeometry(material: MaterialName, geometry: THREE.BufferGeometry) {
    const bucket = this.buckets.get(material) ?? [];
    bucket.push(geometry);
    this.buckets.set(material, bucket);
  }
  box(
    material: MaterialName,
    x: number,
    y: number,
    z: number,
    width: number,
    height: number,
    depth: number,
    solid = false,
    rotationY = 0,
  ) {
    if (width <= 0 || height <= 0 || depth <= 0) return;
    this.position.set(x, y, z);
    this.scale.set(width, height, depth);
    this.quaternion.setFromAxisAngle(new THREE.Vector3(0, 1, 0), rotationY);
    this.matrix.compose(this.position, this.quaternion, this.scale);
    this.addGeometry(material, this.unitBox.clone().applyMatrix4(this.matrix));
    // Only axis-aligned furnishings are solid. Rotated structural decorations
    // are above the visitor; their footprint is not used as a collision proxy.
    if (solid)
      this.colliders.push({
        minX: x - width / 2,
        maxX: x + width / 2,
        minZ: z - depth / 2,
        maxZ: z + depth / 2,
        minY: y - height / 2,
        maxY: y + height / 2,
      });
  }
  cylinder(
    material: MaterialName,
    x: number,
    y: number,
    z: number,
    radius: number,
    height: number,
    solid = false,
  ) {
    this.matrix.makeScale(radius, height, radius).setPosition(x, y, z);
    this.addGeometry(
      material,
      this.unitCylinder.clone().applyMatrix4(this.matrix),
    );
    if (solid)
      this.colliders.push({
        minX: x - radius,
        maxX: x + radius,
        minZ: z - radius,
        maxZ: z + radius,
        minY: y - height / 2,
        maxY: y + height / 2,
      });
  }
  beam(
    material: MaterialName,
    a: THREE.Vector3,
    b: THREE.Vector3,
    size: number,
  ) {
    const direction = b.clone().sub(a);
    this.quaternion.setFromUnitVectors(
      new THREE.Vector3(0, 1, 0),
      direction.clone().normalize(),
    );
    this.matrix.compose(
      a.clone().add(b).multiplyScalar(0.5),
      this.quaternion,
      new THREE.Vector3(size, direction.length(), size),
    );
    this.addGeometry(material, this.unitBox.clone().applyMatrix4(this.matrix));
  }
  floor(
    minX: number,
    maxX: number,
    minZ: number,
    maxZ: number,
    y = 0,
    material: MaterialName = "stone",
  ) {
    if (maxX <= minX || maxZ <= minZ) return;
    this.floors.push({ minX, maxX, minZ, maxZ, y });
    this.box(
      material,
      (minX + maxX) / 2,
      y - 0.15,
      (minZ + maxZ) / 2,
      maxX - minX,
      0.3,
      maxZ - minZ,
    );
  }
  rail(x1: number, z1: number, x2: number, z2: number, y: number) {
    const length = Math.hypot(x2 - x1, z2 - z1);
    const dx = x2 - x1,
      dz = z2 - z1;
    this.beam(
      "metal",
      new THREE.Vector3(x1, y + 1.12, z1),
      new THREE.Vector3(x2, y + 1.12, z2),
      0.065,
    );
    this.box(
      "glass",
      (x1 + x2) / 2,
      y + 0.56,
      (z1 + z2) / 2,
      Math.max(0.07, Math.abs(dx)),
      1.05,
      Math.max(0.07, Math.abs(dz)),
    );
    this.colliders.push({
      minX: Math.min(x1, x2) - 0.09,
      maxX: Math.max(x1, x2) + 0.09,
      minZ: Math.min(z1, z2) - 0.09,
      maxZ: Math.max(z1, z2) + 0.09,
      minY: y,
      maxY: y + 1.2,
    });
    const count = Math.max(1, Math.ceil(length / 2));
    for (let i = 0; i <= count; i++)
      this.box(
        "metal",
        x1 + (dx * i) / count,
        y + 0.57,
        z1 + (dz * i) / count,
        0.055,
        1.14,
        0.055,
      );
  }
  sign(
    text: string,
    x: number,
    y: number,
    z: number,
    width: number,
    height = 0.7,
    facing = 0,
  ) {
    if (typeof document === "undefined") return;
    const canvas = document.createElement("canvas");
    canvas.width = 1024;
    canvas.height = 160;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    ctx.fillStyle = "#203b43";
    ctx.fillRect(0, 0, 1024, 160);
    ctx.fillStyle = "#f0ebdc";
    ctx.font = "500 52px system-ui, sans-serif";
    ctx.textAlign = "center";
    ctx.textBaseline = "middle";
    ctx.fillText(text, 512, 81, 956);
    const texture = new THREE.CanvasTexture(canvas);
    texture.colorSpace = THREE.SRGBColorSpace;
    const material = new THREE.MeshStandardMaterial({
      map: texture,
      roughness: 0.75,
      emissive: 0xffffff,
      emissiveMap: texture,
      emissiveIntensity: 0.15,
    });
    const mesh = new THREE.Mesh(
      new THREE.PlaneGeometry(width, height),
      material,
    );
    mesh.position.set(x, y, z);
    mesh.rotation.y = facing;
    this.group.add(mesh);
  }
  display(id: string, title: string, x: number, z: number, y = 0) {
    this.box("metal", x, y + 0.72, z, 0.1, 1.44, 0.1);
    this.box("darkWood", x, y + 1.35, z, 1.15, 0.7, 0.1, true);
    this.sign(title, x, y + 1.35, z + 0.061, 1.08, 0.6);
    this.displays.push({ id, x, y: y + 1.35, z: z + 0.12 });
  }
  light(x: number, y: number, z: number, intensity = 360) {
    this.box("metal", x, y + 0.07, z, 1.4, 0.15, 0.65);
    this.box("light", x, y - 0.025, z, 1.23, 0.04, 0.5);
    const light = new THREE.PointLight(0xffe7c5, intensity, 35, 1.5);
    light.position.set(x, y - 0.25, z);
    light.userData.interiorLight = true;
    light.userData.baseIntensity = intensity;
    this.group.add(light);
  }
  table(x: number, z: number, y = 0, seats = true) {
    this.box("timber", x, y + 0.74, z, 1.6, 0.09, 0.9, true);
    for (const dx of [-0.65, 0.65])
      for (const dz of [-0.32, 0.32])
        this.box("metal", x + dx, y + 0.35, z + dz, 0.055, 0.7, 0.055);
    if (seats)
      for (const dz of [-0.95, 0.95])
        this.chair(x, z + dz, y, dz > 0 ? 0 : Math.PI);
  }
  chair(x: number, z: number, y = 0, rotation = 0) {
    this.box("fabric", x, y + 0.44, z, 0.5, 0.1, 0.5, true);
    this.box(
      "timber",
      x,
      y + 0.72,
      z + Math.cos(rotation) * 0.22,
      0.5,
      0.55,
      0.055,
    );
    for (const dx of [-0.19, 0.19])
      for (const dz of [-0.19, 0.19])
        this.box("metal", x + dx, y + 0.21, z + dz, 0.035, 0.42, 0.035);
  }
  bench(x: number, z: number, width = 2.2, y = 0) {
    this.box("timber", x, y + 0.46, z, width, 0.13, 0.65, true);
    this.box("timber", x, y + 0.77, z - 0.27, width, 0.5, 0.07);
    for (const dx of [-width * 0.35, width * 0.35])
      this.box("metal", x + dx, y + 0.22, z, 0.12, 0.44, 0.55);
  }
  finish(kind: ArchitectureKind): Architecture {
    for (const [name, geometries] of this.buckets) {
      const geometry = mergeGeometries(geometries, false);
      if (!geometry) throw new Error(`Could not merge ${kind} ${name}`);
      geometry.computeBoundingSphere();
      const mesh = new THREE.Mesh(geometry, this.materials[name]);
      mesh.name = `${kind}-${name}`;
      mesh.castShadow = name !== "glass" && name !== "light" && name !== "net";
      mesh.receiveShadow = name !== "glass" && name !== "light";
      if (name === "roof") mesh.userData.roof = true;
      this.group.add(mesh);
      for (const part of geometries) part.dispose();
    }
    this.unitBox.dispose();
    this.unitCylinder.dispose();
    this.group.name = `${kind}-reference-reconstruction`;
    return {
      group: this.group,
      colliders: this.colliders,
      floors: this.floors,
      ramps: this.ramps,
      displays: this.displays,
      entry: [0, this.depth / 2 + 2],
      interiorBounds: { width: this.width, depth: this.depth },
    };
  }
}

/** Front entrance stays physically open, with glazing either side and a lintel. */
function shell(
  b: Builder,
  height: number,
  sideMaterial: MaterialName = "concrete",
  sideGlazing = false,
) {
  const w = b.width,
    d = b.depth,
    gap = 4.4;
  b.floor(-w / 2, w / 2, -d / 2, d / 2);
  b.box(sideMaterial, 0, height / 2, -d / 2, w, height, 0.3, true);
  for (const x of [-w / 2, w / 2]) {
    b.box(sideMaterial, x, 0.6, 0, 0.3, 1.2, d, true);
    b.box(
      sideGlazing ? "glass" : sideMaterial,
      x,
      (height + 1.2) / 2,
      0,
      0.2,
      height - 1.2,
      d,
      true,
    );
    for (let z = -d / 2; z <= d / 2; z += 4)
      b.box("metal", x, height / 2, z, 0.18, height, 0.12);
  }
  const paneWidth = (w - gap) / 2;
  for (const side of [-1, 1]) {
    const x = side * (gap / 2 + paneWidth / 2);
    b.box("glass", x, 1.8, d / 2, paneWidth, 3.6, 0.15, true);
    b.box(
      sideGlazing ? "glass" : sideMaterial,
      x,
      (height + 3.6) / 2,
      d / 2,
      paneWidth,
      Math.max(0.2, height - 3.6),
      0.3,
      true,
    );
  }
  b.box("metal", 0, 3.7, d / 2, gap, 0.28, 0.35, true);
  for (const x of [-gap / 2, gap / 2])
    b.box("metal", x, 1.8, d / 2, 0.16, 3.6, 0.23, true);
  // Recessed open leaves are visible beside the opening, never across it.
  for (const x of [-2.35, 2.35])
    b.box("glass", x, 1.7, d / 2 - 0.8, 0.08, 3.4, 1.6);
  b.box("metal", 0, 3.9, d / 2 + 0.8, 6.2, 0.16, 2.2);
  b.floor(-3.2, 3.2, d / 2, d / 2 + 3, 0, "concrete");
}

function net(
  b: Builder,
  x1: number,
  z1: number,
  x2: number,
  z2: number,
  height: number,
) {
  const length = Math.hypot(x2 - x1, z2 - z1);
  const a = new THREE.Vector3(),
    c = new THREE.Vector3();
  // 18 cm squares are geometry, so the nets remain transparent without alpha
  // sorting or large textures. All strands merge into one inexpensive draw.
  const divisions = Math.ceil(length / 0.18);
  for (let i = 0; i <= divisions; i++) {
    const x = x1 + ((x2 - x1) * i) / divisions,
      z = z1 + ((z2 - z1) * i) / divisions;
    b.beam("net", a.set(x, 0.12, z), c.set(x, height, z), 0.012);
  }
  for (let y = 0.18; y < height; y += 0.18)
    b.beam("net", a.set(x1, y, z1), c.set(x2, y, z2), 0.012);
  b.beam("metal", a.set(x1, height, z1), c.set(x2, height, z2), 0.045);
  b.colliders.push({
    minX: Math.min(x1, x2) - 0.03,
    maxX: Math.max(x1, x2) + 0.03,
    minZ: Math.min(z1, z2) - 0.03,
    maxZ: Math.max(z1, z2) + 0.03,
    minY: 0,
    maxY: height,
  });
}

function rose(b: Builder) {
  const w = b.width,
    d = b.depth,
    h = b.sourceHeight ?? 8.8;
  shell(b, h, "timber");
  b.box("turf", 0, 0.025, -1.8, w - 0.8, 0.05, d - 4.4);
  b.box("roof", 0, h + 0.2, 0, w + 0.8, 0.4, d + 0.8);
  // The public photos show a dark hall and a timber-clad entrance volume.
  for (const side of [-1, 1]) {
    b.box("roof", side * (w / 2 + 0.18), h / 2, -d * 0.13, 0.1, h, d * 0.73);
    for (let z = -d / 2 + 0.2; z < d * 0.22; z += 0.5)
      b.box("metal", side * (w / 2 + 0.25), h / 2, z, 0.08, h, 0.06);
  }
  for (let x = -w / 2 + 0.3; x < w / 2; x += 0.38)
    b.box("darkWood", x, 6.5, d / 2 + 0.18, 0.075, 3.5, 0.08);
  b.box("white", 0, 4.25, d / 2 + 0.22, w, 0.7, 0.12);
  b.sign(
    "ROSE INDOOR TRAINING CENTRE",
    0,
    4.24,
    d / 2 + 0.3,
    Math.min(w - 1, 15),
    0.6,
  );
  b.box("glass", w * 0.22, 6.4, d / 2 + 0.25, w * 0.34, 2.5, 0.1);
  for (let z = -d / 2 + 3; z < d / 2 - 1; z += 6) {
    for (const x of [-w / 2 + 0.4, w / 2 - 0.4])
      b.box("timber", x, h / 2, z, 0.32, h, 0.44);
    b.box("timber", 0, h - 0.45, z, w - 0.5, 0.6, 0.25);
    b.box("metal", 0, h - 1, z, w - 0.5, 0.07, 0.07);
  }
  // Four independently enterable net enclosures. The long dimension is kept
  // along the building's long axis; central circulation remains at least 2 m.
  const longX = w > d,
    length = Math.max(w, d),
    cross = Math.min(w, d);
  const cageLength = Math.max(7, (length - 9) / 2);
  const cageWidth = Math.max(3, (cross - 7) / 2);
  const point = (u: number, v: number): [number, number] =>
    longX ? [u, v] : [v, u];
  for (let row = 0; row < 2; row++)
    for (let col = 0; col < 2; col++) {
      const u0 = -length / 2 + 2 + row * (cageLength + 2);
      const v0 = -(2 * cageWidth + 2.2) / 2 + col * (cageWidth + 2.2);
      const [ax, az] = point(u0, v0),
        [bx, bz] = point(u0 + cageLength, v0);
      const [cx, cz] = point(u0 + cageLength, v0 + cageWidth),
        [dx, dz] = point(u0, v0 + cageWidth);
      net(b, ax, az, bx, bz, 4.4);
      net(b, bx, bz, cx, cz, 4.4);
      net(b, cx, cz, dx, dz, 4.4);
      // A generous 2.4 m opening at the near end allows real entry.
      if (cageWidth > 3.2) {
        const [ex, ez] = point(u0, v0 + cageWidth - 2.4);
        net(b, ax, az, ex, ez, 4.4);
      }
      const [mx, mz] = point(u0 + cageLength * 0.75, v0 + cageWidth / 2);
      b.box("clay", mx, 0.065, mz, longX ? 2.2 : 1.2, 0.08, longX ? 1.2 : 2.2);
      b.box("white", mx, 0.115, mz, 0.35, 0.025, 0.35);
      const [px, pz] = point(u0 + cageLength * 0.22, v0 + cageWidth / 2);
      b.cylinder("blue", px, 0.8, pz, 0.3, 0.45, true);
      for (const dx of [-0.24, 0.24])
        b.box("metal", px + dx, 0.35, pz, 0.05, 0.7, 0.05);
    }
  // Two pitching mounds occupy the clear front cross aisle. Original screens.
  for (const x of [-w * 0.27, w * 0.27]) {
    const z = d / 2 - 3.2;
    b.box("clay", x, 0.13, z, 2.4, 0.26, 1.7, true);
    b.box("white", x, 0.27, z - 0.35, 0.6, 0.025, 0.15);
    b.box("blue", x - 1.5, 1, z - 1, 0.08, 2, 0.08);
    b.box("blue", x - 0.5, 1.9, z - 1, 2, 0.08, 0.08);
  }
  b.display("rose-info", "BASEBALL TRAINING", 2.8, d / 2 - 2.1);
  b.bench(-w / 2 + 3, d / 2 - 1.2, 3);
  b.light(-w * 0.22, h - 1.2, -d * 0.23, 500);
  b.light(w * 0.22, h - 1.2, d * 0.2, 500);
  for (let z = -d / 2 + 3; z < d / 2; z += 6)
    b.box("light", 0, h - 0.7, z, 1.6, 0.05, 0.5);
}

function shelf(b: Builder, x: number, z: number, length = 5.8) {
  const books: MaterialName[] = [
    "redBook",
    "goldBook",
    "blueBook",
    "whiteBook",
    "greenBook",
  ];
  b.box("timber", x, 0.92, z, 1.05, 1.84, 0.12, true);
  for (const end of [-1, 1])
    b.box("timber", x, 0.92, z + (end * length) / 2, 1.08, 1.84, 0.09);
  for (let level = 0; level < 4; level++) {
    const y = 0.2 + level * 0.43;
    b.box("timber", x, y, z, 1.1, 0.055, length);
    for (let i = 0; i < Math.floor(length / 0.19); i++)
      for (const side of [-1, 1]) {
        const index = (i + level * 3) % books.length;
        const bookHeight = 0.25 + ((i * 7 + level) % 5) * 0.024;
        b.box(
          books[index],
          x + side * 0.3,
          y + bookHeight / 2 + 0.04,
          z - length / 2 + 0.16 + i * 0.19,
          0.39,
          bookHeight,
          0.12 + (i % 3) * 0.018,
        );
      }
  }
  // Shelf collision includes books and feet, not just its thin spine.
  b.colliders.push({
    minX: x - 0.6,
    maxX: x + 0.6,
    minZ: z - length / 2 - 0.1,
    maxZ: z + length / 2 + 0.1,
    minY: 0,
    maxY: 1.85,
  });
}

